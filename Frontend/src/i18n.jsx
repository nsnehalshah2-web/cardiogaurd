const LanguageContext = createContext(null);

function storedLanguage() {
  try { return localStorage.getItem(LANG_KEY) === 'hi' ? 'hi' : 'en'; } catch { return 'en'; }
}

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(storedLanguage);
  useEffect(() => {
    document.documentElement.lang = lang;
    try { localStorage.setItem(LANG_KEY, lang); } catch { /* private mode */ }
  }, [lang]);
  const t = (key, vars = {}) => {
    const text = strings[lang][key] ?? strings.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
  };
  return <LanguageContext.Provider value={{ lang, setLang, t }}>{children}</LanguageContext.Provider>;
}

export function useT() {
  return useContext(LanguageContext);
}

export function LanguageToggle({ className = '' }) {
  const { lang, setLang, t } = useT();
  return <button type="button" className={`btn btn-ghost lang-toggle ${className}`} onClick={() => setLang(lang === 'en' ? 'hi' : 'en')} aria-label="Change language">
    {t('lang.switch')}
  </button>;
}
